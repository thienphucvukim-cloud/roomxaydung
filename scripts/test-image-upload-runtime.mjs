import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const origin = process.env.TIPOOK_TEST_ORIGIN || 'http://127.0.0.1:8788';
assert.ok(['localhost','127.0.0.1'].includes(new URL(origin).hostname),'Use isolated local resources only');
const webp = readFileSync(new URL('./fixtures/upload.webp',import.meta.url));
const png = readFileSync('public/community-house.png');
const registered = await fetch(origin+'/api/auth/register',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({username:'images_'+crypto.randomUUID().slice(0,8),password:'fixture-password-123',name:'Image Fixture'})});
assert.equal(registered.status,200,await registered.clone().text());
const cookie=registered.headers.getSetCookie().find(value=>value.startsWith('tipook_auth_session=')).split(';')[0];
const json=async(path,body,status)=>{
  const response=await fetch(origin+path,{method:'POST',headers:{cookie,'content-type':'application/json'},body:JSON.stringify(body)});
  const result=await response.json();assert.equal(response.status,status,JSON.stringify(result));return result;
};
const upload=async(bytes,type,name,purpose,status=201,path='/api/files')=>{
  const form=new FormData();form.set('file',new File([bytes],name,{type}));if(purpose)form.set('purpose',purpose);
  const response=await fetch(origin+path,{method:'POST',headers:{cookie},body:form});
  const result=await response.json();assert.equal(response.status,status,JSON.stringify(result));return result.attachment||result;
};
await upload(png,'image/png','original.png','drawing-preview',415);
await upload(png,'application/octet-stream','hidden.bin',undefined,415);
await upload(png.subarray(0,64),'image/webp','fake.webp','comment-image',400);
await upload(new Uint8Array(512*1024+1),'image/webp','large.webp',undefined,413);
await upload(new Uint8Array(256*1024+1),'image/webp','large.webp','comment-image',413);
const postImage=await upload(webp,'image/webp','photo.jpg','drawing-preview');
assert.equal(postImage.name,'photo.webp');assert.equal(postImage.type,'image/webp');
const downloaded=await fetch(origin+postImage.url);
assert.equal(downloaded.headers.get('content-type'),'image/webp');assert.deepEqual(Buffer.from(await downloaded.arrayBuffer()),webp);
const created=await json('/api/posts',{category:'Bảng tin',content:'Local optimized image fixture',attachments:[{...postImage,type:'image/png'}]},201);
assert.equal(created.post.attachments[0].type,'image/webp','Persist authoritative R2 MIME type');
await json('/api/comments',{postId:created.post.id,imageKey:postImage.key},400);
const commentImage=await upload(webp,'image/webp','comment.webp','comment-image');
const comment=await json('/api/comments',{postId:created.post.id,imageKey:commentImage.key},201);
assert.ok(comment.comment.imageUrl);
const listed=await fetch(origin+'/api/comments?postId='+created.post.id);
assert.equal((await listed.json()).comments[0].imageKey,commentImage.key);
await json('/api/model-comments',{targetId:'image-fixture-'+crypto.randomUUID(),imageKey:commentImage.key},201);
await upload(png,'image/png','avatar.png',undefined,415,'/api/avatar');
await upload(webp,'image/webp','avatar.webp',undefined,200,'/api/avatar');
const added=await upload(webp,'image/webp','added.webp','drawing-preview');
const edited=await fetch(origin+'/api/my-posts',{method:'PATCH',headers:{cookie,'content-type':'application/json'},body:JSON.stringify({id:created.post.id,imageKeys:[postImage.key,added.key]})});
assert.equal(edited.status,200,await edited.clone().text());
console.log('PASS: raw/spoofed/oversize images denied; WebP stored and served; image-only post, new photo edits, post/model image comments and avatar uploads work in the production build.');
